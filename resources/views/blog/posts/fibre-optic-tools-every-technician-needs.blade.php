<p>Fibre-to-the-home (FTTH) installations need the right tools to be done quickly and reliably. Here are the essential fibre optic tools every technician should carry.</p>

<h2>1. Fusion splicer</h2>
<p>A <a href="/fibre-optic/splicing-machines/">fusion splicer</a> joins two fibre ends with heat. It is the biggest investment in a fibre toolkit but essential for low-loss, permanent splices. Look for models with fast splice times and reliable loss estimation.</p>

<h2>2. Fibre cleaver</h2>
<p>A good cleaver produces clean, flat fibre ends before splicing or connectorising. The quality of the cleave directly affects splice and connector loss, so it is worth buying a reliable one.</p>

<h2>3. Optical power meter</h2>
<p>An <a href="/fibre-optic/optical-power-meters/">optical power meter</a> measures the light power in a fibre link and is used to verify loss budgets and confirm a link is working within spec.</p>

<h2>4. Visual fault locator (VFL)</h2>
<p>A VFL is a red laser that lets you trace fibre, find breaks and verify continuity. It is inexpensive and invaluable for troubleshooting.</p>

<h2>5. OTDR (for larger networks)</h2>
<p>An Optical Time Domain Reflectometer maps the whole fibre run and shows splices, connectors and faults with distance. It is more expensive but valuable for larger FTTH and backbone networks.</p>

<h2>6. Strippers, scissors and consumables</h2>
<p>You will also need fibre strippers, Kevlar scissors, alcohol and lint-free wipes for cleaning, and a steady supply of <a href="/fibre-optic/pigtails/">pigtails</a>, <a href="/fibre-optic/fast-connectors/">fast connectors</a> and <a href="/fibre-optic/plc-splitters/">PLC splitters</a>.</p>

